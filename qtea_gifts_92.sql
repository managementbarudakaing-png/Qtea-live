DROP TABLE IF EXISTS qtea_gifts;
CREATE TABLE qtea_gifts (
  id INT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  price INT NOT NULL COMMENT 'Harga dalam Koin',
  type ENUM('JP','MURNI') NOT NULL,
  category VARCHAR(50),
  is_jackpot BOOLEAN DEFAULT FALSE,
  winrate DECIMAL(5,2) COMMENT 'Persentase winrate JP',
  mult_min INT COMMENT 'Kelipatan minimal',
  mult_max INT COMMENT 'Kelipatan maksimal',
  host_beans INT COMMENT 'Host dapat 60%',
  platform_beans INT COMMENT 'Platform dapat (Murni only)',
  jackpot_pool_beans INT COMMENT 'Masuk pool jackpot (JP only)',
  image_url VARCHAR(255),
  animation_type VARCHAR(50) DEFAULT 'normal' COMMENT 'normal, grand, legendary',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

